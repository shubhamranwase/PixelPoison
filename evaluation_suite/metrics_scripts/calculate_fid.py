import os
import subprocess
import sys
import glob
import io
if isinstance(sys.stdout, io.TextIOWrapper):
    sys.stdout.reconfigure(encoding='utf-8')

def calculate_fid(clean_dir, generated_dir):
    print("="*60)
    print(" FID (Fréchet Inception Distance) EVALUATION ".center(60))
    print("="*60)
    print(f"Baseline (Clean) Dataset: {os.path.relpath(clean_dir)}")
    print(f"Generated Outputs:        {os.path.relpath(generated_dir)}\n")
    
    clean_images = [f for f in glob.glob(os.path.join(clean_dir, "*.*")) if not f.endswith('.gitkeep')]
    gen_images = [f for f in glob.glob(os.path.join(generated_dir, "*.*")) if not f.endswith('.gitkeep')]
    
    if not clean_images:
        print(f"Error: Dataset directory '{clean_dir}' is empty.")
        print("Please add your original pristine images there.")
        return
        
    if not gen_images:
        print(f"Error: Generated outputs directory '{generated_dir}' is empty.")
        print("Please add the images generated by your AI (LoRA) there.")
        return

    print(f"Found {len(clean_images)} baseline images and {len(gen_images)} generated outputs.")
    print("\nRunning pytorch-fid (this downloads InceptionV3 weights if first time)...")
    print("Please wait, calculating multi-dimensional feature distances...\n")
    
    try:
        # Run the pytorch-fid module via subprocess
        result = subprocess.run(
            [sys.executable, "-m", "pytorch_fid", clean_dir, generated_dir],
            capture_output=True,
            text=True,
            check=True
        )
        print(result.stdout)
        
        # Parse the FID score from output
        fid_score = None
        for line in result.stdout.split('\n'):
            if "FID:" in line:
                try:
                    fid_score = float(line.split("FID:")[1].strip())
                except ValueError:
                    pass
                break
                
        if fid_score is not None:
            print("="*60)
            print(f"FINAL FID SCORE: {fid_score:.2f}".center(60))
            print("="*60)
            
            if fid_score > 150:
                print("\n✅ ABSOLUTE FAILURE OF AI: The generated images are completely ruined.")
                print("   The anti-AI protection successfully destroyed the style transfer!")
            elif fid_score > 80:
                print("\n✅ SUCCESS: The AI failed to accurately replicate the artistic style.")
                print("   The outputs are severely degraded compared to the baseline.")
            elif fid_score > 40:
                print("\n⚠️ PARTIAL: The AI struggled, but managed to capture some style elements.")
            else:
                print("\n❌ POOR PROTECTION: The AI successfully replicated the artistic style.")
                print("   A low FID score means the generated images look exactly like the originals.")
                
    except subprocess.CalledProcessError as e:
        print("Error running pytorch-fid:")
        print(e.stderr)

if __name__ == "__main__":
    clean = os.path.join(os.path.dirname(__file__), '..', 'dataset_clean')
    generated = os.path.join(os.path.dirname(__file__), '..', 'lora_outputs')
    calculate_fid(clean, generated)
